const TRANSLATIONS: Record<Lang, Dict> = { en, fr, es, de, tr, ur };

/** Pure translator: look up a key for a language, fall back to English, then the key itself. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return s;
}

/** Hook returning a `t` bound to the active app language (re-renders on language change). */
export function useT() {
  const lang = useSettingsStore((s) => s.language);
  return (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
