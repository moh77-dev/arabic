/**
 * Lightweight localization. `t(key)` returns the string for the active app language, falling back
 * to English for any key a language hasn't translated yet — so screens migrate to i18n incrementally
 * without ever showing a blank. The active language lives in the settings store; `useT()` subscribes
 * to it so components re-render when the user switches languages.
 */
export type Lang = 'en' | 'fr' | 'es' | 'de' | 'tr' | 'ur';

export const SUPPORTED_LANGUAGES: { code: Lang; label: string; native: string; rtl?: boolean }[] = [
  { code: 'en', label: 'English', native: 'English' },
  { code: 'fr', label: 'French', native: 'Français' },
  { code: 'es', label: 'Spanish', native: 'Español' },
  { code: 'de', label: 'German', native: 'Deutsch' },
  { code: 'tr', label: 'Turkish', native: 'Türkçe' },
  { code: 'ur', label: 'Urdu', native: 'اردو', rtl: true },
];

/** Maps the onboarding "native language" labels to language codes. Unknown → English. */
export function labelToLang(label: string | null | undefined): Lang {
  const found = SUPPORTED_LANGUAGES.find((l) => l.label === label);
  return found?.code ?? 'en';
}

